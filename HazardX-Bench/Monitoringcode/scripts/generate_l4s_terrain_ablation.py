"""Generate only A1--A3; existing full-modal configs serve as A4."""
from copy import deepcopy
from pathlib import Path
import json
import yaml

ROOT = Path(__file__).resolve().parents[1]
CONFIG_ROOT = ROOT / 'configs/landslide/l4s'
VARIANTS = {
    'A1': (list(range(12)), None),
    'A2': (list(range(12)) + [13], [None, 12]),  # S2 + DEM
    'A3': (list(range(12)) + [12], [12, None]),  # S2 + Slope
}


def main():
    out = CONFIG_ROOT / 'terrain_ablation'
    out.mkdir(exist_ok=True)
    manifest = []
    for model in ('unet', 'galileo_nano'):
        base = yaml.safe_load((CONFIG_ROOT / f'seg_{model}.yaml').read_text())
        for variant, (indices, topography) in VARIANTS.items():
            cfg = deepcopy(base)
            cfg['model']['kwargs']['in_channels'] = len(indices)
            if model == 'galileo_nano':
                cfg['model']['kwargs']['topographic_channel_indices'] = topography
                cfg['model']['kwargs']['checkpoint_path'] = str(ROOT / 'pretrained_weight/Galileo_nano_encoder.pt')
            for split in ('train', 'val', 'test'):
                ds = cfg['dataset'][split]
                ds['dataset_path'] = '/root/workcsc/datasets/1landslide4sense'
                ds['data_list_path'] = str(ROOT / f'scripts/data_prep/landslide/Landslide4Sense/{split}.txt')
                ds['channel_indices'] = indices
            cfg['output_dir'] = str(ROOT / f'output/l4s/terrain_ablation/seg_{model}_{variant}')
            cfg['experiment'] = dict(ablation=variant, dem=variant == 'A2',
                                     slope=variant == 'A3', input_channels=len(indices))
            path = out / f'seg_{model}_{variant}.yaml'
            path.write_text('# Generated by scripts/generate_l4s_terrain_ablation.py\n' +
                            yaml.safe_dump(cfg, sort_keys=False))
            manifest.append(dict(model=model, variant=variant, input_channels=len(indices),
                                 original_channel_indices=indices, topographic_channel_indices=topography,
                                 config=str(path.relative_to(ROOT))))
    (out / 'manifest.json').write_text(json.dumps(manifest, indent=2))
    print(f'Generated {len(manifest)} configurations (A1--A3 only): {out}')


if __name__ == '__main__':
    main()
