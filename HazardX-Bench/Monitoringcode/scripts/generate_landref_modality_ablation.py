"""Generate B1--B4 configs from the existing LANDREF U-Net/Galileo configs."""
from copy import deepcopy
from pathlib import Path
import json
import yaml

ROOT = Path(__file__).resolve().parents[1]
CONFIG_ROOT = ROOT / 'configs/landslide/landref_cd'
OPTICAL = ('B02', 'B03', 'B04', 'B05', 'B06', 'B07', 'B08', 'B8A', 'B11', 'B12')
SAR = ('gVV', 'gVH', 'COHVV', 'ALPHA', 'ANISOTROPY', 'ENTROPY')
VARIANTS = {'B1': (False, False, 20), 'B2': (True, False, 32),
            'B3': (False, True, 22), 'B4': (True, True, 34)}


def main():
    out = CONFIG_ROOT / 'modality_ablation'
    out.mkdir(exist_ok=True)
    manifest = []
    for model in ('unet', 'galileo_nano'):
        base = yaml.safe_load((CONFIG_ROOT / f'cd_{model}.yaml').read_text())
        for variant, (use_sar, use_terrain, count) in VARIANTS.items():
            cfg = deepcopy(base)
            source = base['dataset']['input']
            target = cfg['dataset']['input']
            for branch, prefix in [('pre', 'PRE1'), ('post', 'POST1')]:
                wanted = {f'{prefix}_{name}' for name in OPTICAL + (SAR if use_sar else ())}
                if branch == 'pre' and use_terrain:
                    wanted.update(('None_DEM', 'None_SLOPE'))
                indices = [i for i, name in enumerate(source[f'{branch}_features']) if name in wanted]
                for field in ('features', 'scales', 'clip_min', 'clip_max'):
                    key = f'{branch}_{field}'
                    target[key] = [source[key][i] for i in indices]
            names = target['pre_features'] + target['post_features']
            assert len(names) == count
            cfg['model']['kwargs']['in_channels'] = count
            if model == 'galileo_nano':
                kw = cfg['model']['kwargs']
                for key in ('s2_channel_indices', 's2_band_names', 'topographic_channel_indices'):
                    kw.pop(key, None)
                kw['feature_names'] = names
                cfg['model']['name'] = 'galileo_landref'
            cfg.pop('compatibility_note', None)
            cfg['output_dir'] = str(ROOT / 'output/landref/modality_ablation' / f'cd_{model}_{variant}')
            cfg['experiment'] = dict(ablation=variant, sar=use_sar, terrain=use_terrain,
                                     effective_channels=count)
            path = out / f'cd_{model}_{variant}.yaml'
            path.write_text('# Generated by scripts/generate_landref_modality_ablation.py\n' +
                            yaml.safe_dump(cfg, sort_keys=False))
            manifest.append(dict(config=str(path.relative_to(ROOT)), model=model,
                                 variant=variant, channels=count, feature_names=names))
    (out / 'manifest.json').write_text(json.dumps(manifest, indent=2))
    print(f'Generated {len(manifest)} configurations in {out}')


if __name__ == '__main__':
    main()
